-- Contact messages are written server-side with the secret key only: no grant and no policy for anon.
create table public.contact_messages (
  id bigint generated by default as identity primary key,
  name text not null,
  email text not null,
  message text not null,
  locale text not null check (locale in ('pl', 'en')),
  ip_hash text not null,
  created_at timestamptz not null default now()
);

alter table public.contact_messages enable row level security;

grant select, insert on public.contact_messages to service_role;
